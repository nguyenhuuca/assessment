-- History of scheduled-job runs (plan-job-run-history). One row per run, written when the run ends;
-- the service keeps the latest 100 rows per job and deletes older ones after each insert.
CREATE TABLE job_run
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name    VARCHAR(64) NOT NULL REFERENCES scheduled_job (name) ON DELETE CASCADE,
    run_trigger VARCHAR(16) NOT NULL,
    result      VARCHAR(16) NOT NULL,
    started_at  TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ NOT NULL,
    duration_ms BIGINT      NOT NULL,
    error       VARCHAR(512)
);

CREATE INDEX idx_job_run_job_started ON job_run (job_name, started_at DESC, id DESC);
