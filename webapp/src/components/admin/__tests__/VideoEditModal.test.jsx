import React from 'react'
import { describe, it, expect, vi } from 'vitest'
import { render, screen, fireEvent } from '@testing-library/react'
import VideoEditModal from '../VideoEditModal.jsx'

const video = { id: 4, title: 'Old title', description: 'Old desc' }

function setup(props = {}) {
  const onSave = vi.fn()
  const onCancel = vi.fn()
  render(<VideoEditModal video={video} onSave={onSave} onCancel={onCancel} {...props} />)
  return {
    onSave,
    onCancel,
    title: screen.getByLabelText('Tiêu đề'),
    desc: screen.getByLabelText('Mô tả'),
    save: screen.getByRole('button', { name: 'Lưu' }),
  }
}

describe('VideoEditModal', () => {
  it('opens with the current values and Save disabled while nothing changed', () => {
    const { title, desc, save } = setup()
    expect(title).toHaveValue('Old title')
    expect(desc).toHaveValue('Old desc')
    expect(save).toBeDisabled()
  })

  it('disables Save when the title is blank', () => {
    const { title, save } = setup()
    fireEvent.change(title, { target: { value: '   ' } })
    expect(save).toBeDisabled()
  })

  it('disables Save and inputs limits while pending', () => {
    const { title, save } = setup({ pending: true })
    fireEvent.change(title, { target: { value: 'New' } })
    expect(save).toBeDisabled()
  })

  it('sends trimmed values on save', () => {
    const { title, desc, save, onSave } = setup()
    fireEvent.change(title, { target: { value: '  New title  ' } })
    fireEvent.change(desc, { target: { value: '  ' } })
    expect(save).not.toBeDisabled()
    fireEvent.click(save)
    expect(onSave).toHaveBeenCalledWith({ title: 'New title', description: '' })
  })

  it('caps the inputs at 200 and 2000 characters', () => {
    const { title, desc } = setup()
    expect(title).toHaveAttribute('maxLength', '200')
    expect(desc).toHaveAttribute('maxLength', '2000')
  })

  it('closes on Esc and on the backdrop, but not while pending', () => {
    const first = setup()
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(first.onCancel).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('dialog').parentElement)
    expect(first.onCancel).toHaveBeenCalledTimes(2)
  })

  it('ignores Esc while pending', () => {
    const { onCancel } = setup({ pending: true })
    fireEvent.keyDown(window, { key: 'Escape' })
    expect(onCancel).not.toHaveBeenCalled()
  })

  it('warns that an empty description is regenerated by the scheduled job', () => {
    setup()
    expect(screen.getByText(/tác vụ định kỳ/)).toBeInTheDocument()
  })

  it('shows the server error', () => {
    setup({ error: 'Title is required' })
    expect(screen.getByRole('alert')).toHaveTextContent('Title is required')
  })
})
